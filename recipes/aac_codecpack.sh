# aac_codecpack.sh -- the OPTIONAL AAC codec pack. AAC is a grey area (patent pools still license it), so it is
# published as SOURCE + these build instructions only and never goes into a prebuilt image; whoever builds it decides
# for themselves.
#
# Runs INSIDE a toolchain container (README.md; env.sh lists the environment). It fetches FFmpeg (pinned release,
# SHA-256 checked; LGPL 2.1+) into $PHOREPOC_BUILD/codecpack/ffmpeg-src, configures ONLY its AAC decoder + parser
# (portable C: no assembly, no threads), and writes $PHOREPOC_BUILD/codecpack/ariheaacdecwrapper.mmp: OUR decoder
# library for the release's Aricent HE-AAC plug-in (os/src/codecs/ariheaacdecwrapper) + the FFmpeg sources it needs
# (paths relative to that mmp). The rest of the AAC chain (the AAC controller, the Aricent plug-in) is the 2010
# release's own code. The registry entries are in registry/components_codecpack.py.
set -eu
VER=6.1.2
SHA256=3b624649725ecdc565c903ca6643d41f33bd49239922e45c9b1442c63dca4e38
. "$(dirname "$0")/env.sh"
fetch "https://ffmpeg.org/releases/ffmpeg-$VER.tar.xz" "ffmpeg-$VER.tar.xz" "$SHA256"

SRC=$CP/ffmpeg-src
if [ ! -f "$SRC/configure" ]; then
  mkdir -p "$SRC"
  tar -xf "$DL/ffmpeg-$VER.tar.xz" -C "$SRC" --strip-components=1
fi
cd "$SRC"
# FFT tables only up to what AAC uses (else ~17 MB of static data per process: ffmpeg_small_tx.py)
python3 "$RECIPES/ffmpeg_small_tx.py" "$SRC"
# ... and no 12 KB VLC scratch on an 8 KB controller-thread stack (ffmpeg_small_stack.py)
python3 "$RECIPES/ffmpeg_small_stack.py" "$SRC"
./configure --disable-everything --enable-decoder=aac --enable-parser=aac \
  --disable-programs --disable-doc --disable-avdevice --disable-avformat --disable-swscale --disable-swresample \
  --disable-avfilter --disable-postproc --disable-network --disable-pthreads --disable-w32threads \
  --disable-os2threads --disable-asm --disable-x86asm --disable-inline-asm --disable-iconv --disable-zlib \
  --disable-bzlib --disable-lzma --disable-debug --disable-runtime-cpudetect --disable-hwaccels --disable-vaapi \
  --disable-vdpau --disable-autodetect > "$CP/aac-configure.log" 2>&1 || { tail -20 "$CP/aac-configure.log"; exit 1; }
# LGPL only, never GPL/version3/nonfree
grep -qx 'License: LGPL version 2.1 or later' "$CP/aac-configure.log" || { echo "configure licence line is not LGPL 2.1+"; grep -i '^License' "$CP/aac-configure.log"; exit 1; }
# configure probed the CONTAINER's glibc; the board's C library is P.I.P.S./Open C: what it lacks is switched off
# (FFmpeg then uses its own fallbacks: libavutil/libm.h, mem.c's plain malloc)
for h in GETAUXVAL MMAP MEMALIGN POSIX_MEMALIGN SYSCONF ISATTY STRERROR_R LOCALTIME_R GMTIME_R CLOCK_GETTIME \
         NANOSLEEP USLEEP ARC4RANDOM GETRANDOM PRCTL MALLOC_H LOG2F LOG2; do
  sed -i "s/^#define HAVE_$h 1$/#define HAVE_$h 0/" config.h
done
# the sources the AAC decoder + parser need (libavcodec core, libavutil core; not the crypto/hash/video helpers the
# stock libavutil also builds)
CODEC="aac_ac3_parser aac_parser aacdec aacps_common aacps_float aacpsdsp_float aacsbr aactab adts_header adts_parser
  allcodecs avcodec avpacket bitstream bitstream_filters bsf cbrt_data codec_desc codec_par decode encode get_buffer kbdwin
  mathtables mpeg4audio mpeg4audio_sample_rates options parser parsers profiles refstruct sbrdsp sinewin utils version
  vlc"
UTIL="avstring bprint buffer channel_layout cpu crc dict error eval fifo float_dsp frame hwcontext hwcontext_stub
  imgutils intmath log log2_tab mathematics mem opt parseutils pixdesc rational reverse samplefmt time tx tx_double
  tx_float tx_int32 utils version avsscanf"
MMP=$CP/ariheaacdecwrapper.mmp
{
  echo "// GENERATED by recipes/aac_codecpack.sh -- OUR HE-AAC decoder library over FFmpeg $VER (LGPL 2.1+)"
  echo "TARGET		ariheaacdecwrapper.dll"
  echo "TARGETTYPE	dll"
  echo "UID		0x1000008d 0xE701571C"
  echo "CAPABILITY	ALL -Tcb"
  echo "VENDORID	0"
  echo "DEFFILE		../osview/src/codecs/ariheaacdecwrapper/eabi/ariheaacdecwrapperu.def"
  echo "SOURCEPATH	../osview/src/codecs/ariheaacdecwrapper/src"
  echo "SOURCE		ariheaacdecwrapper.cpp"
  echo "SOURCEPATH	ffmpeg-src/libavcodec"
  for f in $CODEC; do echo "SOURCE		$f.c"; done
  echo "SOURCEPATH	ffmpeg-src/libavutil"
  for f in $UTIL; do echo "SOURCE		$f.c"; done
  # the release's ariheaacdecwrapper.h (export_hdr) is put on the include path by the registry entry
  echo "USERINCLUDE	ffmpeg-src"
  echo "OS_LAYER_SYSTEMINCLUDE"
  echo "OS_LAYER_LIBC_SYSTEMINCLUDE"
  echo "LIBRARY		euser.lib libc.lib libm.lib"
} > "$MMP"
echo "FFmpeg $VER configured (AAC decoder + parser); $(grep -c '^SOURCE' "$MMP") sources -> $MMP"
